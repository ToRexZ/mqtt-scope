export const ICONS = Object.keys(PATHS);

export function icon(name, size = 14) {
  const span = document.createElement('span');
  span.className = `icon icon-${name}`;
  span.setAttribute('aria-hidden', 'true');
  span.innerHTML = `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${PATHS[name]}</svg>`;
  return span;
}

// A button showing only an icon; `title` doubles as its accessible name.
export function iconButton(name, title, onClick, className = 'btn icon') {
  const b = document.createElement('button');
  b.type = 'button'; // never the implicit submit button of a surrounding form
  b.className = className;
  b.title = title;
  b.setAttribute('aria-label', title);
  b.append(icon(name));
  b.addEventListener('click', onClick);
  return b;
}

// Swaps the icon shown by an icon button.
export function setIcon(buttonEl, name) {
  buttonEl.querySelector('.icon')?.replaceWith(icon(name));
}
